'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined });
  try {
    const page = await browser.newPage();
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    await page.route('https://**/*', route => route.abort());
    await page.route('http://**/*', route => route.abort());
    await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
    await page.waitForFunction(() => window.RVApp && window.RVApp.state.ready);
    assert.equal(await page.evaluate(() => typeof window.mermaid), 'undefined');
    const source = ['# System', '', '```mermaid', 'flowchart TD', ' T["Telegram bot"] --> W["Cloudflare Worker · Hono"]', ' A["Mini App · Preact"] --> W', ' C["Cron trigger"] --> W', ' W --> L["Shared accounting and access rules"]', ' L --> D["D1 · ledger and encrypted cards"]', '```', '', '```mermaid', 'sequenceDiagram', ' participant U as کاربر', ' participant S as Server', ' U->>S: سلام', ' S-->>U: OK', '```'].join('\n');
    await page.evaluate(text => { window.RVApp.setDoc(text, 'system.md'); window.RVApp.setMode('preview'); }, source);
    await page.waitForFunction(() => document.querySelectorAll('#preview .diagram-figure img').length === 2);
    await page.waitForFunction(() => Array.from(document.querySelectorAll('#preview .diagram-figure img')).every(img => img.complete && img.naturalWidth > 0));
    assert.equal(requests.filter(url => url.endsWith('/vendor/mermaid/mermaid.full.js')).length, 1);
    assert.ok(!requests.some(url => /^https?:/.test(url)), 'diagrams render offline, without font or CDN requests');
    assert.equal(await page.locator('#editor').inputValue(), source);
    const firstUrl = await page.locator('#preview .diagram-figure img').first().getAttribute('src');
    const firstSvg = decodeURIComponent(firstUrl.slice(firstUrl.indexOf(',') + 1));
    assert.match(firstSvg.replace(/<[^>]+>/g, ''), /Telegram bot/);
    assert.match(firstSvg.replace(/<[^>]+>/g, '').replace(/\s/g, ''), /ledgerandencryptedcards/);
    const overlay = page.locator('#preview .diagram-tools').first();
    assert.equal(await overlay.locator('button').first().textContent(), '');
    await page.mouse.move(0, 0);
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('#preview .diagram-tools')).opacity) < .8);
    await overlay.hover();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#preview .diagram-tools')).opacity === '1');
    await page.mouse.move(0, 0); await overlay.getByRole('button', { name: 'Source', exact: true }).focus();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#preview .diagram-tools')).opacity === '1');
    await page.locator('#preview .diagram-tools button').first().click();
    assert.equal(await page.locator('#preview pre').first().isVisible(), true);
    const expand = page.locator('#preview .diagram-tools').first().getByRole('button', { name: 'Expand', exact: true });
    await expand.click();
    await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
    assert.equal(await page.locator('.diagram-canvas img').evaluate(img => img.style.width), '125%');
    await page.keyboard.press('Escape');
    await page.waitForSelector('.diagram-dialog', { state: 'detached' });
    assert.equal(await expand.evaluate(node => node === document.activeElement), true);
    await page.evaluate(() => { window.RVApp.newTab('```mermaid\nflowchart LR\nX-->Y\n```', 'second.md'); window.RVApp.showComparison(); });
    await page.waitForFunction(() => document.querySelector('#comparisonPreview .diagram-figure img'));
    await page.locator('#btnTheme').click();
    await page.locator('#btnTheme').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await page.evaluate(async () => { await window.RV.Diagrams.render(document.getElementById('preview')); await window.RV.Diagrams.render(document.getElementById('comparisonPreview')); });
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 900 });
      await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
      for (const mode of ['preview', 'split']) {
        await page.evaluate(async value => { window.RVApp.setMode(value); await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); await window.RV.Diagrams.render(document.getElementById('preview')); }, mode);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${mode} remains within viewport ${width}`);
        const images = await page.locator('.diagram-figure img').evaluateAll(nodes => nodes.map(node => ({ width: node.getBoundingClientRect().width, parent: node.parentElement.clientWidth })));
        assert.ok(images.every(img => img.width > 0 && img.width <= img.parent + 1), JSON.stringify({width, mode, images}));
        const overlays = await page.locator('.diagram-figure').evaluateAll(nodes => nodes.map(node => {
          const figure = node.getBoundingClientRect(), tools = node.querySelector('.diagram-tools').getBoundingClientRect(), image = node.querySelector('img').getBoundingClientRect();
          return { contained: tools.left >= figure.left && tools.right <= figure.right + 1, above: tools.bottom <= image.top + 1, position: getComputedStyle(node.querySelector('.diagram-tools')).position };
        }));
        assert.ok(overlays.every(item => item.contained && item.above && item.position === 'absolute'), JSON.stringify({width, mode, overlays}));
      }
    }
    await page.setViewportSize({ width: 1200, height: 900 });
    const saved = page.waitForEvent('download');
    await page.locator('#preview .diagram-tools').first().getByRole('button', { name: 'Save SVG', exact: true }).click();
    const file = await saved;
    assert.match(file.suggestedFilename(), /diagram\.svg/);
    const svg = await fs.readFile(await file.path(), 'utf8');
    assert.match(svg, /<svg/); assert.doesNotMatch(svg, /<script|foreignObject/);
    // Export while the first diagram render is still pending, then check the self-contained result.
    await page.evaluate(text => window.RVApp.setDoc(text, 'export.md'), source + '\nNew export.');
    const exported = page.waitForEvent('download'); await page.locator('#btnExport').click();
    const htmlFile = await exported, html = await fs.readFile(await htmlFile.path(), 'utf8');
    assert.match(html, /data:image\/svg\+xml/); assert.doesNotMatch(html, /class="diagram-tools"|<script/);
    const temp = await fs.mkdtemp(path.join(require('node:os').tmpdir(), 'readme-diagram-export-'));
    const exportPath = path.join(temp, 'document.html'); await fs.writeFile(exportPath, html);
    const standalone = await browser.newPage(); await standalone.goto(pathToFileURL(exportPath).href);
    await standalone.waitForFunction(() => Array.from(document.querySelectorAll('.diagram-figure img')).length === 2 && Array.from(document.querySelectorAll('.diagram-figure img')).every(img => img.complete && img.naturalWidth > 0));
    await standalone.close(); await fs.rm(temp, { recursive: true, force: true });
    await page.evaluate(() => window.RVApp.setDoc('```mermaid\nthis is invalid\n```', 'bad.md'));
    await page.waitForSelector('#preview .diagram-message');
    assert.equal(await page.locator('#preview pre').isVisible(), true);
    assert.equal(await page.evaluate(() => window.RVApp.state.dirty), false);
    const demo = await fs.readFile(path.resolve(__dirname, '../docs/demo.md'), 'utf8');
    await page.evaluate(() => { window.RVApp.loadSample(); window.RVApp.setMode('preview'); });
    await page.waitForFunction(() => document.querySelectorAll('#preview .diagram-figure img').length === 7 && Array.from(document.querySelectorAll('#preview .diagram-figure img')).every(img => img.complete && img.naturalWidth > 0));
    assert.equal(await page.locator('#editor').inputValue(), demo, 'built-in sample matches the downloadable demo');
    assert.equal(await page.locator('#preview .diagram-message').count(), 0);
    const mathImage = page.locator('#preview .diagram-figure img').last();
    const mathUrl = await mathImage.getAttribute('src');
    const mathSvg = decodeURIComponent(mathUrl.slice(mathUrl.indexOf(',') + 1));
    for (const tag of ['math', 'msup', 'mfrac', 'mtable']) assert.match(mathSvg, new RegExp('<' + tag + '(?:>| )'));
    assert.ok(!mathSvg.includes('$$'), 'formula delimiters are replaced by mathematical structure');
    await page.locator('#preview .diagram-layout select').last().selectOption('elk');
    await page.waitForFunction(() => !document.querySelector('#preview [aria-busy]'));
    const mathSave = page.waitForEvent('download');
    await page.locator('#preview .code-block[data-lang="mermaid"]').last().getByRole('button', { name: 'Save SVG', exact: true }).click();
    const mathFile = await mathSave, savedMath = await fs.readFile(await mathFile.path(), 'utf8');
    assert.match(savedMath, /<mfrac>/); assert.doesNotMatch(savedMath, /<script|<iframe|<img/);
    const mathTemp = await fs.mkdtemp(path.join(require('node:os').tmpdir(), 'readme-math-export-'));
    const mathPath = path.join(mathTemp, 'formula.svg'); await fs.writeFile(mathPath, savedMath);
    const mathPage = await browser.newPage(); await mathPage.goto(pathToFileURL(mathPath).href);
    const fraction = await mathPage.locator('math mfrac').first().evaluate(node => ({ total: node.getBoundingClientRect().height, numerator: node.firstElementChild.getBoundingClientRect().height }));
    assert.ok(fraction.total > fraction.numerator, 'exported fractions actually lay out vertically');
    const matrixRows = await mathPage.locator('math mtable mtr').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().top));
    assert.equal(matrixRows.length, 2); assert.ok(matrixRows[1] > matrixRows[0], 'matrix rows are laid out separately');
    await mathPage.close();
    const mathHtmlDownload = page.waitForEvent('download'); await page.locator('#btnExport').click();
    const mathHtmlFile = await mathHtmlDownload, mathHtml = await fs.readFile(await mathHtmlFile.path(), 'utf8');
    assert.match(mathHtml, /%3Cmath/);
    await fs.writeFile(path.join(mathTemp, 'formula.html'), mathHtml);
    const mathHtmlPage = await browser.newPage(); await mathHtmlPage.goto(pathToFileURL(path.join(mathTemp, 'formula.html')).href);
    await mathHtmlPage.waitForFunction(() => document.querySelectorAll('.diagram-figure img').length === 7 && Array.from(document.querySelectorAll('.diagram-figure img')).every(img => img.complete && img.naturalWidth > 0));
    await mathHtmlPage.close(); await fs.rm(mathTemp, { recursive: true, force: true });
    // Full Mermaid adds mindmaps and architecture; ELK is available without a CDN.
    const fullSource = '```mermaid\nmindmap\n root((README Viewer))\n  Reading\n  Diagrams\n```\n\n```mermaid\narchitecture-beta\n service api(server)[API]\n service db(database)[Database]\n api:R -- L:db\n```\n\n```mermaid\nflowchart LR\n A[Start]-->B[End]\n```';
    await page.evaluate(text => window.RVApp.setDoc(text, 'full.md'), fullSource);
    await page.waitForFunction(() => document.querySelectorAll('#preview .diagram-figure img').length === 3);
    await page.locator('#preview .diagram-layout select').selectOption('elk');
    await page.waitForFunction(() => document.querySelector('#preview .diagram-layout select')?.value === 'elk' && !document.querySelector('#preview [aria-busy]'));
    assert.equal(await page.locator('#preview .diagram-message').count(), 0);
    const mono = await page.locator('#preview pre code').first().evaluate(node => getComputedStyle(node).fontFamily);
    await page.evaluate(() => document.getElementById('btnAppearance').click());
    await page.locator('#fontLatin').fill('Arial');
    await page.locator('#fontPersian').fill('Vazirmatn');
    await page.locator('#fontUi').fill('Arial');
    await page.evaluate(async () => { await window.RV.Fonts.ready(); await window.RV.Diagrams.render(document.getElementById('preview')); });
    assert.equal(await page.evaluate(() => document.fonts.check('16px "RV Document Arabic"', 'سلام')), true);
    assert.match(await page.locator('#preview .diagram-figure img').first().getAttribute('src'), /data%3Afont%2Fwoff2%3Bbase64/);
    assert.equal(await page.locator('#preview pre code').first().evaluate(node => getComputedStyle(node).fontFamily), mono, 'code keeps its monospace font');
    await page.locator('#appearanceCancel').click();
    await page.evaluate(() => window.RV.Fonts.ready());
    assert.equal(await page.evaluate(() => document.documentElement.style.getPropertyValue('--doc-font')), '');
    await page.evaluate(() => document.getElementById('btnAppearance').click());
    await page.locator('#fontPersian').fill('Vazirmatn');
    await page.locator('#appearanceApply').click();
    await page.evaluate(() => window.RV.Fonts.ready());
    const fontExport = page.waitForEvent('download'); await page.locator('#btnExport').click();
    const fontHtmlFile = await fontExport, fontHtml = await fs.readFile(await fontHtmlFile.path(), 'utf8');
    assert.match(fontHtml, /data:font\/woff2;base64/);
    await page.reload(); await page.waitForFunction(() => window.RVApp && window.RVApp.state.ready);
    await page.evaluate(() => window.RV.Fonts.ready());
    assert.equal(await page.evaluate(() => window.RV.Fonts.snapshot().persian), 'Vazirmatn');
    assert.ok(!requests.some(url => /^https?:/.test(url)), 'full engine, ELK and fonts remain offline');
    assert.deepEqual(errors, []);
    console.log('Full Mermaid browser smoke passed: offline diagrams + ELK + mindmap + architecture, fonts preview/cancel/persistence/embedding, mobile, SVG/HTML export.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
